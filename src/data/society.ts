const building = (
  id: string,
  name: string,
  technology: string,
  cost: Cost,
  housing = 0,
  production: Cost = {},
  consumption: Cost = {},
  security = 0,
  knowledge = 0,
): BuildingDefinition => ({
  id,
  name,
  technology,
  cost,
  housing,
  production,
  consumption,
  security,
  knowledge,
  seconds: 15 + Object.values(cost).reduce((a, b) => a + b, 0) * 0.3,
  description: `${housing ? `Housing for ${housing}. ` : ''}${Object.entries(production)
    .map(([k, v]) => `Produces ${v} ${k}/s. `)
    .join(
      '',
    )}${knowledge ? `Generates ${knowledge} knowledge/s. ` : ''}${security ? `Security +${security}.` : ''}`,
});

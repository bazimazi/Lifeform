const adapt = (
  id: string,
  name: string,
  category: string,
  benefit: string,
  tradeoff: string,
  modifiers: Partial<Stats> = {},
  requires: string[] = [],
  organ?: string,
  excludes: string[] = [],
): MutationDefinition => ({
  id,
  name,
  category,
  description: organ
    ? ADVANCED_ORGANS.find((o) => o.id === organ)!.description
    : `${name} develops an existing biological capability.`,
  benefit,
  tradeoff,
  modifiers,
  requires,
  organ,
  excludes,
  cost: 1,
  biomass: 5,
  icon:
    category === 'Movement'
      ? 'wave'
      : category === 'Sensory'
        ? 'eye'
        : category === 'Offense'
          ? 'jaw'
          : category === 'Social'
            ? 'branch'
            : 'cell',
  diet: [],
});
